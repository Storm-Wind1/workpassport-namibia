import assert from "node:assert/strict";
import { chromium } from "playwright";

const base = "http://127.0.0.1:5173";
const browser = await chromium.launch();
try {
  const context = await browser.newContext({ permissions: ["clipboard-read", "clipboard-write"] });
  const page = await context.newPage();
  const main = page.getByRole("main");
  const button = (name) => main.getByRole("button", { name, exact: true });
  const link = (name) => main.getByRole("link", { name, exact: true }).first();
  const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem("workpassport-demo-v1")));

  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base);
  await main.getByRole("button", { name: "Ask WorkPassport" }).waitFor();
  const menu = page.getByRole("button", { name: "Toggle menu" });
  await menu.click();
  await page.getByRole("navigation").getByRole("link", { name: "Help", exact: true }).click();
  await main.locator("summary").first().click();
  assert.equal(await main.locator("details[open]").count(), 1);
  await button("Ask WorkPassport").click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Ask a question").fill("How do I log in again?");
  await dialog.getByRole("button", { name: "Send question" }).click();
  await dialog.getByRole("log").getByText(/Select Log in/).waitFor();
  await dialog.getByRole("button", { name: "Close help" }).click();
  await page.getByRole("contentinfo").getByRole("link", {name:"How it works"}).click();
  await link("Create your demo WorkPassport").click();
  await page.waitForURL("**/join");
  await page.goto(base+"/missing-route");
  await page.getByRole("link",{name:"Go home"}).click();
  await page.waitForURL(base+"/");

  await page.setViewportSize({ width: 1100, height: 850 });
  await page.goto(base+"/dashboard");
  await link("Get started").click();
  await page.waitForURL("**/join");
  await button("Next").click();
  await main.getByLabel("Full name").fill("Demo Worker");
  await main.getByLabel("Email",{exact:true}).fill("demo@example.test");
  await main.getByLabel("Town",{exact:true}).selectOption("Windhoek");
  await button("Next").click();
  await main.getByLabel("Find work",{exact:true}).check();
  await button("Next").click();
  await main.getByRole("checkbox").check();
  await button("Create demo profile").click();
  await page.waitForURL("**/dashboard");
  await button("Edit skills").click();
  await main.getByLabel("Edit your skills").fill("React, Carpentry");
  await button("Save skills").click();
  await main.getByLabel("List my profile in this browser’s worker directory").check();
  await main.getByLabel("Preferred distance from my town").selectOption("50");
  await main.getByLabel("Available for work",{exact:true}).uncheck();
  await main.getByLabel("Available for work",{exact:true}).check();
  await link("View my WorkPassport").click();
  await page.waitForURL("**/passport/*");
  await main.getByText("Carpentry",{exact:true}).waitFor();
  assert.equal(await button("Share WorkPassport").count(),0);
  await link("Dashboard").click();
  await link("Browse opportunities").click();
  await main.getByLabel("Search opportunities").fill("xxx-no-demo-result");
  await main.getByText("No opportunities found").waitFor();
  await button("Clear filters").click();
  for (const label of ["location","category","type"]) {
    const filter = main.getByLabel("Filter by "+label);
    await filter.selectOption({index:1});
    await page.waitForFunction(key=>new URL(location.href).searchParams.has(key),label);
    await button("Clear filters").click();
  }
  await main.getByLabel("Matches my work preferences").check();
  await page.reload();
  await main.getByLabel("Matches my work preferences").waitFor();
  assert.equal(await main.getByLabel("Matches my work preferences").isChecked(),true);
  await button("Clear filters").click();
  await main.locator(".job-card .job-title").first().click();
  await main.getByLabel("Tell us about yourself").fill("I am available to help with this opportunity.");
  await button("Submit demo application").click();
  await main.getByText(/Application saved. View it/).waitFor();
  assert.equal((await saved()).applications.length,1);
  await page.getByRole("navigation").getByRole("link",{name:"Dashboard"}).click();
  await main.getByText("I am available to help with this opportunity.").waitFor();
  await button("Add activity").click();
  await main.getByLabel("Hire help",{exact:true}).check();
  await main.getByLabel("Offer a service",{exact:true}).check();
  await button("Save activities").click();
  await main.getByLabel("Service title").fill("Repair a desk");
  await main.getByLabel("Service starting price").fill("250");
  await button("Add service").click();
  await main.getByText("Repair a desk",{exact:true}).waitFor();
  await link("Find talent").click();
  await main.getByLabel("Search workers").fill("xxxx-no-worker");
  await main.getByText("No matching workers").waitFor();
  await main.getByLabel("Search workers").fill("");
  await main.getByLabel("Worker location").selectOption({index:1});
  await main.getByLabel("Worker location").selectOption("");
  await main.getByLabel("Search workers").fill("Anna");
  await link("View passport").click();
  await button("Share WorkPassport").click();
  await button("Link copied").waitFor();
  assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),page.url());
  await main.getByLabel("What do you need help with?").fill("Please quote for repairing desks.");
  await main.getByLabel("Estimated budget (N$)").fill("500");
  await button("Request demo quotation").click();
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem("workpassport-demo-v1")).quotes.length===1);
  await page.getByRole("navigation").getByRole("link",{name:"Dashboard"}).click();
  await main.getByText("Please quote for repairing desks.").waitFor();
  await link("Post opportunity").click();
  await main.getByLabel("Job title").fill("Repair workshop desks");
  await main.getByLabel("Business or employer").fill("Demo Workshop");
  await main.getByLabel("Pay in N$ (include period)").fill("450 / day");
  await main.getByLabel("About the work").fill("Repair three workshop desks for our community.");
  await main.getByLabel("Skills (separated by commas)").fill("Carpentry");
  await main.getByLabel("Require all listed skills for a recommended match").check();
  await button("Create demo opportunity").click();
  await main.getByText("You posted this opportunity.").waitFor();
  await page.reload();
  await main.getByRole("heading",{name:"Repair workshop desks"}).waitFor();
  await page.getByRole("navigation").getByRole("link",{name:"Trust & Verification"}).click();
  assert.equal(await button("Submit documents — coming later").isDisabled(),true);
  await link("Back to dashboard").click();
  await button("Add activity").click();
  await main.getByLabel("Hire help",{exact:true}).uncheck();
  await main.getByLabel("Offer a service",{exact:true}).uncheck();
  await button("Save activities").click();
  await main.getByText("Please quote for repairing desks.").waitFor();
  assert.equal((await saved()).services.length,1);
  await page.getByRole("button",{name:"Sign out of demo"}).click();
  await page.goto(base+"/talent");
  await main.getByLabel("Search workers").fill("Demo Worker");
  await link("View passport").click();
  await main.getByRole("heading",{name:"Demo Worker"}).waitFor();
  assert.equal(await button("Share WorkPassport").count(),0);
  await page.goto(base+"/post-job");
  await link("Create account").click();
  await page.waitForURL("**/join");
  await main.getByRole("radio",{name:"Business"}).check();
  await button("Next").click();
  for (const [label,value] of [["Business / trading name","Demo Hiring Team"],["Contact person’s name","Demo Owner"],["Business email","owner@example.test"]]) {
    await main.getByLabel(label,{exact:true}).fill(value);
  }
  await main.getByLabel("Industry / category").selectOption("Carpentry");
  await main.getByLabel("City / town").selectOption("Windhoek");
  await button("Next").click();
  await main.getByLabel("Recruit workers").check();
  await button("Next").click();
  await main.getByRole("checkbox").check();
  await button("Create demo profile").click();
  await page.waitForURL("**/dashboard");
  assert.equal(await button("Delegate staff roles — coming later").isDisabled(),true);
  await link("Find talent").click();
  await main.getByLabel("Search workers").fill("Demo Worker");
  await link("View passport").click();
  await main.getByRole("heading",{name:"Demo Worker"}).waitFor();
  await main.getByLabel("What do you need help with?").waitFor();
  await page.getByRole("button",{name:"Sign out of demo"}).click();
  await page.goto(base+"/login");
  await main.getByLabel("Choose a demo profile on this device").selectOption({label:"Demo Worker · Individual"});
  await button("Resume saved demo on this device").click();
  await main.getByLabel("List my profile in this browser’s worker directory").uncheck();
  await page.goto(base+"/talent");
  await main.getByLabel("Search workers").fill("Demo Worker");
  await main.getByText("No matching workers").waitFor();

  // Exercise the root recovery control with a damaged local demo record.
  const original = await page.evaluate(() => localStorage.getItem("workpassport-demo-v1"));
  const firstId = await page.evaluate(() => {
    const data = JSON.parse(localStorage.getItem("workpassport-demo-v1"));
    data.jobs[0].skills = null;
    localStorage.setItem("workpassport-demo-v1", JSON.stringify(data));
    return data.jobs[0].id;
  });
  await page.goto(base+"/opportunities/"+firstId);
  await page.getByRole("heading",{name:"This page didn't load"}).waitFor();
  await page.evaluate(raw => localStorage.setItem("workpassport-demo-v1", raw), original);
  await page.getByRole("button",{name:"Try again"}).click();
  await main.getByRole("heading",{name:"Repair workshop desks"}).waitFor();
} finally {
  await browser.close();
}
